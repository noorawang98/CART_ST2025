mycibersort=function(sig_matrix, 
                     mixture_file, 
                     perm=0, 
                     id2gene=NULL,
                     QN=TRUE,prefix='myfile'){
  
  #read in data
  if(length(grep('gz',mixture_file))>0){
    Y <- read.table(gzfile(mixture_file), header = T, sep = "\t", row.names = 1,check.names = F)
  }else{
    Y <- read.table(mixture_file, header = T, sep = "\t", row.names = 1,check.names = F)
  }
  if(!is.null(id2gene)){
    Y$id = rownames(Y)
    Y = left_join(id2gene,Y,'id')
    Y = Y[,-1]
    Y =aggregate(.~gene,data=Y,sum)
    Y = data.frame(Y,row.names='gene')
  }
  
  X <- read.table(sig_matrix,header = T,sep = "\t",row.names = 1,check.names = F)
  
  X <- data.matrix(X)
  Y <- data.matrix(Y)
  
  #order
  X <- X[order(rownames(X)),]
  Y <- Y[order(rownames(Y)),]
  
  P <- perm #number of permutations
  
  #anti-log if max < 50 in mixture file
  if (max(Y) < 50) {Y <- 2^Y}
  
  #quantile normalization of mixture file
  if (QN == TRUE) {
    tmpc <- colnames(Y)
    tmpr <- rownames(Y)
    Y <- preprocessCore::normalize.quantiles(Y)
    colnames(Y) <- tmpc
    rownames(Y) <- tmpr
  }
  
  # if (substr(Sys.Date(),6,7) > 4) {
  #   next
  # }
  
  #intersect genes
  Xgns <- row.names(X)
  Ygns <- row.names(Y)
  YintX <- Ygns %in% Xgns
  Y <- Y[YintX,]
  XintY <- Xgns %in% row.names(Y)
  X <- X[XintY,]
  
  #standardize sig matrix
  X <- (X - mean(X)) / sd(as.vector(X))
  
  #empirical null distribution of correlation coefficients
  if (P > 0) {nulldist <- sort(doPerm(P, X, Y)$dist)}
  
  #print(nulldist)
  
  header <- c('Mixture',colnames(X),"P-value","Correlation","RMSE")
  #print(header)
  
  output <- matrix()
  itor <- 1
  mixtures <- dim(Y)[2]
  pval <- 9999
  
  #iterate through mixtures
  while (itor <= mixtures) {
    
    y <- Y[,itor]
    
    #standardize mixture
    y <- (y - mean(y)) / sd(y)
    
    #run SVR core algorithm
    result <- CoreAlg(X, y)
    
    # if (substr(Sys.Date(),1,4) > 2019) {
    #   next
    # }
    
    #get results
    w <- result$w
    mix_r <- result$mix_r
    mix_rmse <- result$mix_rmse
    
    #calculate p-value
    if (P > 0) {pval <- 1 - (which.min(abs(nulldist - mix_r)) / length(nulldist))}
    
    #print output
    out <- c(colnames(Y)[itor],w,pval,mix_r,mix_rmse)
    if (itor == 1) {output <- out}
    else {output <- rbind(output, out)}
    
    itor <- itor + 1
    
  }
  
  #save results
  write.table(rbind(header,output), file = paste0(prefix,"-CIBERSORT-Results.txt"), sep = "\t", row.names = F, col.names = F, quote = F)
  
  #return matrix object containing all results
  obj <- rbind(header,output)
  obj <- obj[,-1]
  obj <- obj[-1,]
  obj <- matrix(as.numeric(unlist(obj)),nrow = nrow(obj))
  rownames(obj) <- colnames(Y)
  colnames(obj) <- c(colnames(X),"P-value","Correlation","RMSE")
  return(obj)
}
