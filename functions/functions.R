myCARD = function(sc.ref,st.obj,
                  minCountGene=100,minCountSpot=3,
                  NumGrids=5000,ineibor=10){
  
  sc_count = sc.ref@assays$RNA@counts
  sc_meta = sc.ref@meta.data
  sc_meta$cellType = droplevels(sc_meta$celltype)
  
  sc_meta$sampleInfo = sc_meta$sample
  
  spatial_count = st.obj@assays$RNA@counts
  spatial_location = data.frame(x=st.obj$x,y=st.obj$y)
  
  
  CARD_obj = createCARDObject(
    sc_count = sc_count,
    sc_meta =sc_meta,
    spatial_count = spatial_count,
    spatial_location = spatial_location,
    ct.varname = "cellType",
    ct.select = unique(sc_meta$cellType),
    sample.varname = "sampleInfo",
    minCountGene = minCountGene,
    minCountSpot = minCountSpot) 
  
  CARD_obj = CARD_deconvolution(CARD_object = CARD_obj)
  # CARD_obj = CARD.imputation(CARD_obj,Numsout of memory or near-singularzGrids = NumGrids,ineibor = ineibor,exclude = NULL)
  return(CARD_obj)
}


