  pbmc=FindVariableFeatures(pbmc,nfeatures = nfeatures)
  features = grep("^Gm",features,invert = T,value = T)
  
  ## 使用pca的分解结果降维聚类
  pbmc <- RunPCA(pbmc,
                 features=features)
  set.seed(219)
  # pbmc.pca <- RunUMAP(pbmc, dims = 1:dim) %>% 
  # FindNeighbors(dims = 1:dim) %>% FindClusters(resolution = resolution)
  
