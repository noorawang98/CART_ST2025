#st cluster/pos/distance
cal_zoom_rate = function(width, height){
  std_width = 1000
  std_height = std_width / (46 * 31) * (46 * 36 * sqrt(3) / 2.0)
  if(std_width / std_height > width / height){
    scale = width / std_width
  }
  else{
    scale = height / std_height
  }
  return(scale)
}

